-- ==========================================================================
-- 006_so_instances_drop_status.sql — העמודה `status` יורדת מ-`k_so_instances`
-- ==========================================================================
--
-- ⛔⛔ **מה הקובץ עושה:** ⚠️ גורע את `status` מ-`k_so_instances` — ⭐ העמודה
--    נולדה `'pending'` ⛔ ואיש מעולם לא כתב לה ערך אחר.
--
-- ⛔⛔ **הנימוק:** ⚠️ מסך היבוא היה אמור לסלוק את המופע ולהעביר אותו
--    מ-`pending`, ⭐ **והוא ירד בסבב 161** — ⛔ ומאותו יום כל הוראת קבע
--    נצבעה אפור לנצח: ⚠️ עמודה שאין לה כותב ואין לה קורא היא שארית,
--    ⭐ והשם `pending` נשא כאן משמעות שנייה לזו של תור הסנכרון.
--
-- ⚠️ **והטבלה ריקה** — ⭐ ואין מה להמיר: ⛔ הגריעה אינה נוגעת בשום שורה.
-- ⚠️ אידמפוטנטי — ⭐ `if exists`, ⛔ וריצה שנייה אינה משנה דבר.
-- ⛔ ואפס `drop table` ואפס `truncate` — ⚠️ עמודה אחת, ⭐ ולא טבלה.
--
-- ⚠️ **מצב ההרצה נמדד מול המסד** ⛔ ואינו מוצהר כאן.
-- ==========================================================================

alter table public.k_so_instances drop column if exists status;
