-- ==========================================================================
-- 007_so_instances_future_soft_delete.sql — מופעי הוראת קבע בחודש עתידי יורדים
-- ==========================================================================
--
-- ⛔⛔ **מה הקובץ עושה:** ⚠️ מסמן מחוק כל מופע ב-`k_so_instances` שחודשו
--    עתידי ביחס לחודש העברי של יום ההרצה — ⭐ במחיקה רכה, ⛔ ולא ב-`delete`.
--
-- ⛔⛔ **הנימוק:** ⚠️ הכתיבה נגזרה מהחודש שמוצג ⛔ ולא מהשעון — ⭐ כל חודש
--    שנפתח בניווט קיבל מופעים: ⚠️ מופע עתידי כתוב נקרא כפעולה שקרתה,
--    ⛔ והעתיד נגזר בתצוגה ⛔ ואינו נכתב.
--
-- ⚠️ **ואפס תנועה מקושרת** — ⭐ נמדד מול `k_entries.so_instance_client_id`
--    לפני ההרצה: ⛔ הגריעה אינה משאירה יתום.
-- ⚠️ אידמפוטנטי — ⭐ `and not deleted`, ⛔ וריצה שנייה אינה משנה דבר.
-- ⛔ **והחודש העתידי הראשון מוצהר כאן כליטרל** — ⚠️ `5787-02` הוא חשוון
--    תשפ״ז, ⭐ החודש שאחרי יום ההרצה: ⛔ למסד אין מנוע תאריך עברי.
--
-- ⚠️ **מצב ההרצה נמדד מול המסד** ⛔ ואינו מוצהר כאן.
-- ==========================================================================

update public.k_so_instances
   set deleted = true,
       deleted_at = now(),
       deleted_by = 'round-170',
       updated_at = (extract(epoch from now()) * 1000)::bigint
 where month_key >= '5787-02'
   and not deleted
   and not exists (select 1 from public.k_entries e
                    where e.so_instance_client_id = k_so_instances.client_id);
