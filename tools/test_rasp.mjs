#!/usr/bin/env node
/*  test_rasp.mjs — הפטל בשני מקומות.
 *
 *  **מה נאכף:** ⛔ אסימוני הפטל מיושמים בשני כללי CSS בלבד — ⚠️ הכפתור הצף
 *  ושורת «אין עוד מלבדו!»: ⭐ המדידה היא מונה מול מספר, ⛔ ואיתו השוואת
 *  **שמות הכללים** עצמם · ⛔ **ואפס פטל במחרוזת CSS שנכתבת מ-JS** — ⚠️ ערך
 *  שנבנה בזמן ריצה הוא אתר יישום לכל דבר · ⛔ **והשורה היא זו שנקבעה** —
 *  ⚠️ הטקסט נחלץ מהקבוע ומושווה, ⭐ ולא נבדקת נוכחותו.
 *
 *  **הנימוק המדוד:** ⛔ צבע שמופיע בכל מקום מפסיק להיות סימן — ⚠️ והפטל
 *  הוא הסימן היחיד שמבדיל את שתי נקודות המגע הללו מכל השאר: ⭐ **ונמדד**
 *  שהיה לו אתר יישום שלישי — ⛔ מערך צבעי הפתיתים, ⚠️ שנכתב כמחרוזת CSS
 *  מ-JS ולכן לא נראה בשום סריקה של גיליון הסגנון.
 *
 *  **מה יישבר בלעדיו:** ⛔ כל כלל שיוסיף את הגוון יעבור בשקט — ⚠️ הוא
 *  ייראה תקין בכל מצב ובשני הצבעים, ⭐ והסימן ידהה בהדרגה: ⛔ ואין שער
 *  אחר שסופר אתרי יישום של אסימון בודד.
 *
 *  **מה אינו נאכף כאן:** ⛔ **יחס הניגודיות** — ⚠️ הוא נמדד בשער העיצוב;
 *  ⛔ **וסולמות הגודל והריווח** — ⚠️ הם נמדדים בשער החזותי, ⭐ וכאן נמדד
 *  אסימון אחד ואתריו.
 *
 *  ⛔ שער פרטי לאפליקציה אחת — ⚠️ אסימון זהות שתפקידו להופיע בשני מקומות
 *  בלבד קיים כאן בלבד: ⭐ בשלוש האחיות צבע הזהות הוא `--brand`, ⛔ והוא
 *  צבוע על כל רכיב שמייצג את האפליקציה.
 *  ⛔ **והשער סורק גולמי בכוונה** — ⚠️ הערך החזותי יושב גם בתוך מחרוזת CSS
 *  שנכתבת מ-JS, ⭐ וההלבנה מוחקת בדיוק את מה שהוא מודד: ⛔ ולכן ההיקף
 *  מחולץ תחילה — גיליון הסגנון ואזורי הסקריפט בנפרד, ⚠️ ולא המסמך כולו.
 *  ⛔ המוטציות אינן נכתבות לעץ — ⚠️ השער מקבל את התוכן כארגומנט, ⭐ והן
 *  רצות בזיכרון: ⛔ בלי לכתוב ובלי תהליך.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/* ── APP — הדבר היחיד שנבדל בין הריפו ──────────────────────────────────── */
const APP = {
  app: 'ha-kupa',
  /*  ⛔ שני הכללים שמותר להם את הגוון — ⚠️ **מה נכנס**: בורר CSS ⟵ מה
   *  הוא מצייר; ⛔ **ומה מפיל**: בורר שלישי, ⛔ ובורר מוצהר שאין לו אתר.
   *  ⭐ **ולמה המבנה קיים**: «שני מקומות» הוא מספר, ⚠️ והשמות הם מה
   *  שמונע ממנו לנדוד ⛔ בלי שהמספר ישתנה. */
  sites: { '.opener': 'שורת הפתיחה שבראש כל מסך — ⛔ בתפקיד הדיו', '.fab': 'הכפתור הצף — ⛔ בתפקיד המילוי' },
  inkSite: '.fab',
  tokens: ['--rasp', '--rasp-ink'],
  openerConst: 'MSG_OPENER',
  openerText: 'אין עוד מלבדו!',
  openerClass: 'opener',
};
/* ── סוף APP ───────────────────────────────────────────────────────────── */

/*  ⛔ הקובץ הזה אינו אוכף שורה בטבלת התשתית — ⚠️ הצהרה ריקה ולא היעדר:
 *  ⛔ שער בלי הצהרה אינו נבדל משער שההצהרה שלו נשמטה. */
export const ROWS = [];

/*  ⛔ המוטציות אינן ברירת המחדל — ⚠️ כל מוטציה היא שינוי ⟵ הרצה ⟵ שחזור:
 *  ⛔ הן רצות ברמה המלאה (`--full`), בסוף הסבב ולפני מיזוג. */
const RUN_MUT = process.env.GATE_MUT === '1';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

let failures = 0;
/*  ⛔ שער מריץ את כל טענותיו — ⚠️ תהליך שנסגר באמצע מדפיס «עבר» על טענות
 *  שלא רצו: ⭐ `EXPECTED` הוא רצפה שנמדדה ברמה שבה השער רץ, ⛔ ופחות ממנה
 *  הוא כשל — ⚠️ והמאזין על `exit` תופס גם יציאה שקדמה להמתנה. */
const GATE_ID = new URL(import.meta.url).pathname.split('/').pop();
/*  ⛔ ריצפת הטענות — ⚠️ **מה נכנס**: המשותפת, שהיא מספר זהה בכל הריפו,
 *  ⛔ והפרטית עם היכולת שמוסיפה אותה; ⛔ **ומה מפיל**: משותפת שנבדלת בין
 *  הריפו, פרטית בלי נימוק, וסכום אפס. */
const FLOOR = { shared: 0, app: 9, appWhy: 'אסימון הזהות שתפקידו להופיע בשני מקומות בלבד — ⛔ והוא קיים כאן בלבד: ⚠️ בשאר צבע הזהות נצבע על כל רכיב מייצג' };
const EXPECTED = FLOOR.shared + FLOOR.app;
let RAN = 0;
/*  ⛔ המונה נלכד בכניסה לשלב המוטציות — ⚠️ `null` הוא תהליך שלא הגיע
 *  לשם, ⛔ ואפס הוא שער שכל גופו מוטציות. */
let PRE_MUT = null;
const mutStage = () => { if (PRE_MUT === null) PRE_MUT = RAN; };
/*  ⛔ הדגל נלכד ברישום ⛔ ולא בסגירה — ⚠️ שער שמריץ שער אחר מציב אותו
 *  **אחרי** הרישום. */
const SUBRUN = !!process.env.GATE_SUBRUN;
/*  ⛔ הריצפה נמדדת בשני הכיוונים — ⚠️ פחות מהמוצהר הוא ריצה חלקית,
 *  ⛔ ויותר ממנו הוא ריצפה מיושנת. */
const FLOOR_MAX = (() => {
  const r = /^(\d+)-(\d+)$/.exec(process.env.GATE_FLOOR_RANGE || '');
  return r ? Number(r[2]) : EXPECTED;
})();
process.on('exit', () => {
  if (!process.argv[1] || !process.argv[1].endsWith(GATE_ID)) return;
  if (SUBRUN) return;
  const N = PRE_MUT || RAN;
  console.log(`רצו ${N} מתוך ${EXPECTED}`);
  if (N < EXPECTED) {
    console.error(`❌ ${GATE_ID}: רצו ${N} טענות מתוך ${EXPECTED} מוצהרות — ` +
      'מה עושים: ודא `await` בקריאה הראשית, ⛔ ויציאה שאינה קודמת להמתנה.');
    process.exitCode = 1;
  } else if (N > FLOOR_MAX) {
    console.error(`❌ ${GATE_ID}: רצו ${N}, והריצפה ${EXPECTED} — עדכן את \`FLOOR\`.`);
    process.exitCode = 1;
  }
});
const fail = (m) => { RAN++; failures++; console.error('❌ ' + m); };
const pass = (m) => (RAN++, console.log('✅ ' + m));

const n = (s, re) => (s.match(re) || []).length;

/*  ⛔ שני ההיקפים מופרדים לפני המדידה — ⚠️ **מה נכנס**: גיליון הסגנון
 *  מצד אחד ואזורי הסקריפט מצד שני; ⛔ **ומה מפיל**: היקף ריק — ⭐ סריקה
 *  על מסמך שלא נחתך סופרת הגדרת אסימון כאתר יישום. */
function regions(src) {
  const css = [...src.matchAll(/<style[^>]*>([\s\S]*?)<\/style\s*>/gi)]
    .map((m) => m[1]).join('\n').replace(/\/\*[\s\S]*?\*\//g, ' ');
  /*  ⛔ ההערות נחתכות — ⚠️ הן מתעדות את האיסור עצמו, ⭐ ואינן אתר
   *  יישום: ⛔ **והחיתוך שמרני** — ⚠️ בלוק שלם, ⛔ ושורה שכולה הערה:
   *  ⭐ `//` שבאמצע שורה נשאר, ⛔ שהוא חי בכתובות — ⚠️ וספירת-יתר מפילה
   *  ⛔ ואינה מסתירה. */
  const js = [...src.matchAll(/<script(?![^>]*\ssrc[=\s])[^>]*>([\s\S]*?)<\/script\s*>/gi)]
    .map((m) => m[1]).join('\n')
    .replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/.*$/gm, ' ');
  return { css, js };
}

/*  ⛔ הבורר נגזר מהכלל שבו יושב האתר — ⚠️ ולא ממספר שורה: ⭐ מספר שורה
 *  נשבר בכל הוספה מעליו, ⛔ והבורר הוא מה שהתקן נוקב בו. */
function siteSelectors(css, re) {
  const out = [];
  for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g))
    if (re.test(m[2])) out.push(m[1].trim().split('\n').pop().trim());
  return out;
}

/*  ⛔ **מה נכנס**: שם הטענה ⟵ הערך שנמדד ⟵ הערך הצפוי; ⛔ **ומה מפיל**:
 *  מדידה שאינה הערך הצפוי. ⭐ **ולמה המבנה קיים**: המוטציה רצה על אותו
 *  מרשם בדיוק, ⚠️ ובלעדיו היא הייתה מודדת דבר אחר מזה שהשער מודד — ⛔ ולכן מרשם אחד לשתי הדרכים. */
function checks(src) {
  const { css, js } = regions(src);
  const useRe = /var\(--rasp(?:-ink)?\)/;
  const sel = siteSelectors(css, useRe);
  const want = Object.keys(APP.sites);
  const inkSel = siteSelectors(css, /var\(--on-rasp\)/);
  const openerVal = (new RegExp('var ' + APP.openerConst + " = '([^']*)'").exec(src) || [, ''])[1];
  return [
    ['א · גיליון הסגנון נקרא', n(css, /var\(--/g) > 0 ? 1 : 0, 1, `${n(css, /var\(--/g)} אתרי אסימון`],
    ['ב · שני האסימונים מוגדרים במצב בהיר ובכהה',
     APP.tokens.reduce((s, t) => s + n(css, new RegExp('(?<![\\w-])' + t + '\\s*:', 'g')), 0), 2 * APP.tokens.length],
    ['ג · אתרי היישום של הפטל', sel.length, want.length],
    ['ד · והם בדיוק הכללים שנקבעו', sel.slice().sort().join('+'), want.slice().sort().join('+')],
    ['ה · אתרי הדיו שעל הפטל', inkSel.length, 1],
    ['ו · והדיו יושב על הכפתור הצף', inkSel.join('+'), APP.inkSite],
    ['ז · פטל במחרוזת CSS שנכתבת מ-JS', n(js, /--rasp\b/g), 0],
    ['ח · שורת הפתיחה היא זו שנקבעה', openerVal, APP.openerText],
    ['ט · והיא מצוירת במחלקת הפתיחה',
     n(src, new RegExp('class="' + APP.openerClass + '"', 'g')), 1],
  ];
}

const run = (src) => checks(src).filter(([, got, want]) => got !== want);

console.log(`· ${APP.app} — הפטל בשני מקומות`);
const SRC = rd('index.html');
for (const [name, got, want, extra] of checks(SRC)) {
  if (got === want) pass(`${name} — נמדד «${got}»${extra ? ` (${extra})` : ''}`);
  else fail(`${name} — נמדד «${got}» והצפוי «${want}»${extra ? ` (${extra})` : ''}. ` +
            'מסירים את הגוון מהאתר השלישי — ⛔ הוא הסימן של שני המקומות, ולא ערכה');
}

/* ── מוטציות ───────────────────────────────────────────────────────────── */
mutStage();
if (RUN_MUT) {
  /*  ⛔ המוטציה שוברת את המנגנון ⛔ ולא את הצורה — ⚠️ אתר יישום שלישי הוא
   *  בדיוק מה שהשער בא למנוע, ⭐ והוא נשתל בכלל חי. ⛔ והיא נכתבת על
   *  עותק **בזיכרון**. */
  const third = SRC.replace('.closer{color:var(--purple-5)', '.closer{color:var(--rasp)');
  if (third === SRC) {
    fail('מוטציה · האתר השלישי לא נשתל — נמדדו 0 החלפות והצפוי אחת. ' +
         'מיישרים את תבנית ההחלפה לכלל שבגיליון הסגנון');
  } else {
    const fellOn = run(third);
    const named = fellOn.find(([x]) => x.startsWith('ג ·'));
    if (named)
      pass(`מ1 · מוטציה: אתר יישום שלישי מפיל את הטענה «${named[0]}» — ` +
           `${fellOn.length} טענות מתוך ${checks(SRC).length} התהפכו`);
    else
      fail('מ1 · מוטציה: אתר יישום שלישי ⛔ לא הפיל את טענה ג — נמדדו ' +
           `${fellOn.length} טענות שהתהפכו והצפוי את הטענה הנקובה. מחזירים את ספירת האתרים`);
  }

  /*  ⛔ מוטציית-נגד היא שינוי חי שאסור לו להפיל — ⚠️ כלל שנוסף וצובע
   *  מאסימון אחר, ⭐ ולא הוספת הערה. */
  const added = SRC.replace('.opener{color:var(--rasp-ink)',
                            '.kp-mut{color:var(--purple-3)}\n.opener{color:var(--rasp-ink)');
  if (added === SRC) {
    fail('מוטציית-נגד · הכלל לא נוסף — נמדדו 0 החלפות והצפוי אחת. ' +
         'מיישרים את תבנית ההחלפה לכלל שבגיליון הסגנון');
  } else {
    const badOnes = run(added);
    if (!badOnes.length)
      pass('נ1 · ⭐ מוטציית-נגד: כלל שנוסף וצובע מאסימון אחר ⛔ אינו מפיל אף טענה');
    else
      fail(`נ1 · מוטציית-נגד הפילה את הטענה «${badOnes[0][0]}» — נמדדו ${badOnes.length} ` +
           'טענות שהתהפכו והצפוי אפס. מצמצמים את המדידה לאסימוני הפטל בלבד');
  }
}

if (failures) { console.error(`\n❌ ${APP.app}: ${failures} טענות נכשלו`); process.exitCode = 1; }
else console.log(`\n✓ ${APP.app}: הפטל בשני מקומות`);
